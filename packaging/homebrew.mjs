// Writes the Homebrew formula for one release from its SHA256SUMS:
//   node packaging/homebrew.mjs <version> <SHA256SUMS> > Formula/devguard.rb
// The formula installs the release's standalone build for the Mac or Linux
// machine it runs on; it needs git at run time.
import { readFileSync } from "node:fs";

const [version, sumsFile] = process.argv.slice(2);
if (!/^\d+\.\d+\.\d+$/.test(version ?? "") || !sumsFile) {
	console.error("usage: node packaging/homebrew.mjs <version, e.g. 0.1.0> <SHA256SUMS>");
	process.exit(2);
}
const sums = new Map(readFileSync(sumsFile, "utf8").trim().split("\n").map((line) => {
	const [hash, file] = line.split(/\s+/);
	return [file, hash];
}));
const asset = (platform) => {
	const name = `devguard-${platform}.tar.gz`;
	const hash = sums.get(name) ?? (process.env.DEVGUARD_FORMULA_PARTIAL === "1" ? "0".repeat(64) : undefined);
	if (!/^[0-9a-f]{64}$/.test(hash ?? "")) throw new Error(`SHA256SUMS has no hash for ${name}`);
	// DEVGUARD_DOWNLOAD_BASE points at local files in the packaging check.
	const base = process.env.DEVGUARD_DOWNLOAD_BASE ?? `https://github.com/n8watkins/devguard/releases/download/v${version}`;
	return `      url "${base}/${name}"\n      sha256 "${hash}"`;
};

process.stdout.write(`# Generated by packaging/homebrew.mjs in n8watkins/devguard for v${version}; do not edit.
class Devguard < Formula
  desc "Run many AI coding agents at once without running out of memory, ports or disk"
  homepage "https://github.com/n8watkins/devguard"
${process.env.DEVGUARD_DOWNLOAD_BASE ? `  version "${version}" # local files carry no version in their URL\n` : ""}  license "MIT"

  depends_on "git"

  on_macos do
    on_arm do
${asset("darwin-arm64")}
    end
    on_intel do
${asset("darwin-x64")}
    end
  end

  on_linux do
    on_arm do
${asset("linux-arm64")}
    end
    on_intel do
${asset("linux-x64")}
    end
  end

  def install
    # Homebrew unpacks the archive into its devguard/ folder: the program plus its runtime.
    libexec.install Dir["*"]
    bin.install_symlink libexec/"devguard"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/devguard --version")
    assert_match(/^\\d+$/, shell_output("#{bin}/devguard port #{testpath}").strip)
  end
end
`);
